// Автотесты чистого движка фигур с вырезами: node tests/cut.test.mjs
// Ненулевой exit-код при провале. DOM не нужен — движок это src/cut/_engine.js.

import { parse, build, pick } from '../src/cut/_engine.js';

let failed = 0, passed = 0;

function eq(actual, expected, label) {
    let a = JSON.stringify(actual), e = JSON.stringify(expected);
    if (a === e) { passed++; return; }
    failed++;
    console.error(`FAIL: ${label}\n  ожидалось: ${e}\n  получено:  ${a}`);
}

// ---------------------------------------------------------------------------
// Разбор пути Figma
// ---------------------------------------------------------------------------

eq(parse('100 50 | M10 0H100V50H0V10Z'), { w: 100, h: 50, points: [[10, 0], [100, 0], [100, 50], [0, 50], [0, 10]] },
    'M H V Z: абсолютные точки');
eq(parse('100 50 | M10 0L100 0 100 50 0 50Z').points.length, 4, 'L с несколькими парами');
eq(parse('20 20 | M0 0H20V20C20 20 10 20 0 20Z').points.at(-1), [0, 20], 'C: берётся конечная точка');
eq(parse('20 20 | M0 0H20V20Q10 20 0 20Z').points.at(-1), [0, 20], 'Q: берётся конечная точка');
eq(parse('594 237 | M10.4 1L1 10.2V134.4Z').points[0], [10.4, 1], 'дробные координаты');
eq(parse(''), null, 'пустое значение');
eq(parse('100 | M0 0H1V1Z'), null, 'нет высоты');
eq(parse('100 50 M0 0'), null, 'нет разделителя |');
eq(parse('100 50 | M0 0H10'), null, 'меньше трёх точек');

// ---------------------------------------------------------------------------
// Привязка к ближнему краю
// ---------------------------------------------------------------------------

let shape = parse('100 50 | M10 0H100V40L90 50H0V0Z');
eq(build(shape, 100, 50), 'M10 0L100 0L100 40L90 50L0 50L0 0Z', 'размер как в макете — путь не меняется');
eq(build(shape, 300, 80), 'M10 0L300 0L300 70L290 80L0 80L0 0Z', 'шире и выше: вырезы того же размера у своих краёв');
eq(build(shape, 300, 80, 2), 'M20 0L300 0L300 60L280 80L0 80L0 0Z', 'k = 2: вырезы вдвое больше');
eq(build(parse('10 10 | M0 0H10V10H0Z'), 33.333, 10), 'M0 0L33.33 0L33.33 10L0 10Z', 'округление до сотых');

// ---------------------------------------------------------------------------
// Фигура для ширины окна
// ---------------------------------------------------------------------------

let bps = { md: 768, lp: 1024, lg: 1280 };
let variants = { base: 'B', md: 'M', lg: 'G' };
eq(pick(variants, bps, 375), 'B', 'уже первого брейкпоинта — base');
eq(pick(variants, bps, 800), 'M', 'от md');
eq(pick(variants, bps, 1100), 'M', 'lp без своей фигуры — остаётся md');
eq(pick(variants, bps, 1440), 'G', 'от lg');
eq(pick({ base: 'B', lp: null }, bps, 1440), 'B', 'нераспознанная фигура брейкпоинта пропускается');
eq(pick({ base: 'B', zz: 'Z' }, bps, 1440), 'B', 'ключ не из шкалы пропускается');
eq(pick({ base: 'B', lg: 'G', md: 'M' }, bps, 1440), 'G', 'порядок ключей не важен');

console.log(`${passed} passed, ${failed} failed`);
process.exit(failed ? 1 : 0);
