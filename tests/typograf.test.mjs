// Автотесты правил Typograf: node tests/typograf.test.mjs
// Ненулевой exit-код при провале. DOM не нужен — движок src/typograf/_engine.js
// работает со строками. В ожиданиях «~» означает неразрывный пробел.

import { RULES, glue, text } from '../src/typograf/_engine.js';

let failed = 0, passed = 0;

function eq(actual, expected, label) {
    let a = JSON.stringify(actual), e = JSON.stringify(expected);
    if (a === e) { passed++; return; }
    failed++;
    console.error(`FAIL: ${label}\n  ожидалось: ${e}\n  получено:  ${a}`);
}

const nb = s => s.replace(/~/g, ' ');
const off = { last_word: false };

// t(вход, ожидание, подпись, правила) — по умолчанию без last_word, чтобы видеть правило в чистом виде
const t = (input, expected, label, rules = off) => eq(text(input, rules), nb(expected), label);

// ---------------------------------------------------------------------------
// Предлоги, союзы, частицы — к следующему слову
// ---------------------------------------------------------------------------

t('жил в доме', 'жил в~доме', 'предлог');
t('В доме', 'В~доме', 'с заглавной');
t('в доме', 'в~доме', 'в начале строки');
t('шёл к дому и в сад', 'шёл к~дому и~в~сад', 'цепочка «и в»');
t('а и в доме', 'а~и~в~доме', 'три подряд');
t('сказал «в доме»', 'сказал «в~доме»', 'после открывающей кавычки');
t('(на столе)', '(на~столе)', 'после скобки');
t('"на столе"', '"на~столе"', 'после прямой кавычки');
t('[на столе]', '[на~столе]', 'после квадратной скобки');
t('для всех', 'для~всех', 'длинный предлог');
t('благодаря тебе', 'благодаря~тебе', 'составной предлог');
t('но не сейчас', 'но~не~сейчас', 'союз и частица');
t('ни шагу', 'ни~шагу', 'ни');
t('вот он', 'вот~он', 'вот');
t('слово в, конце', 'слово в, конце', 'пунктуация после короткого слова — не клеится');
t('пошёл в.', 'пошёл в.', 'точка после — не клеится');
t('слово доме', 'слово доме', 'обычные слова не клеятся');
t('свод вода', 'свод вода', 'короткое слово внутри длинного — не клеится');
t('кто-то пришёл', 'кто-то пришёл', 'то в дефисном слове не трогается');
t('в\n        доме', 'в~доме', 'многострочный пробел → один NBSP');
t('в \t доме', 'в~доме', 'табы и пробелы → один NBSP');
t('в', 'в', 'одно короткое слово');
t('в ', 'в ', 'хвостовой пробел не трогается');
t('  в доме  ', '  в~доме  ', 'ведущие и хвостовые пробелы сохраняются');
t('', '', 'пустая строка');
t('   ', '   ', 'только пробелы');

// ---------------------------------------------------------------------------
// Частицы — к предыдущему слову
// ---------------------------------------------------------------------------

t('он же сказал', 'он~же сказал', 'же');
t('был бы рад', 'был~бы рад', 'бы');
t('знал ли он', 'знал~ли он', 'ли');
t('пришёл б раньше', 'пришёл~б раньше', 'б');
t('Он же.', 'Он~же.', 'частица с точкой');
t('Был ли?', 'Был~ли?', 'частица с вопросом');
t('ну же, давай', 'ну~же, давай', 'частица с запятой; ну — вперёд');
t('ведь он же', 'ведь~он~же', 'ведь — вперёд, же — назад');
t('же', 'же', 'частица одна');
t('жесть была', 'жесть была', 'же внутри слова');

// ---------------------------------------------------------------------------
// Числа
// ---------------------------------------------------------------------------

t('2024 год', '2024~год', 'число и слово');
t('10 000 рублей', '10~000~рублей', 'разряды');
t('в 5 часов', 'в~5~часов', 'предлог и число');
t('1, 2, 3', '1, 2, 3', 'после запятой — не клеится');
t('шаг 3', 'шаг 3', 'слово перед числом — не клеится');
t('COVID-19 вирус', 'COVID-19~вирус', 'число в конце куска');
t('10 000 руб', '10 000~руб', 'авторский NBSP цел');
t('10 000 руб', '10 000~руб', 'авторский узкий пробел цел');

// ---------------------------------------------------------------------------
// Тире
// ---------------------------------------------------------------------------

t('Москва — столица', 'Москва~— столица', 'длинное тире');
t('2010 – 2020', '2010~– 2020', 'короткое тире (и число)');
t('слово - слово', 'слово~- слово', 'дефис как тире');
t('из-за угла', 'из-за угла', 'дефис внутри слова — не тире');
t('Москва —', 'Москва~—', 'тире в конце');
t('— Да, — сказал он', '— Да,~— сказал он', 'прямая речь');

// ---------------------------------------------------------------------------
// Сокращения
// ---------------------------------------------------------------------------

t('то есть т. е. так', 'то~есть т.~е. так', 'т. е.');
t('и т. д.', 'и~т.~д.', 'и т. д.');
t('и т. п. Потом', 'и~т.~п. Потом', 'после «п.» разрыв допустим');
t('г. Москва', 'г.~Москва', 'г.');
t('ул. Ленина', 'ул.~Ленина', 'ул.');
t('дом № 5', 'дом №~5', '№');
t('см. рис. 3', 'см.~рис.~3', 'см. рис.');
t('§ 12', '§~12', 'параграф');
t('5 млн руб.', '5~млн~руб.', 'млн после числа');
t('Г. Москва', 'Г.~Москва', 'сокращение с заглавной (и инициал)');

// ---------------------------------------------------------------------------
// Инициалы
// ---------------------------------------------------------------------------

t('А. С. Пушкин', 'А.~С.~Пушкин', 'инициалы перед фамилией');
t('Пушкин А. С.', 'Пушкин~А.~С.', 'инициалы после фамилии');
t('J. R. R. Tolkien', 'J. R.~R.~Tolkien', 'латиница: 16 символов > max_chain, дальняя связь отпущена');
t('J. R. R. Tolkien', 'J.~R.~R.~Tolkien', 'латиница без предела', { last_word: false, max_chain: 0 });
t('писал А. Блок о', 'писал А.~Блок о', 'один инициал');
t('пункт а. потом', 'пункт а. потом', 'строчная буква с точкой — не инициал');

// ---------------------------------------------------------------------------
// Последнее слово
// ---------------------------------------------------------------------------

const last = (input, expected, label) => eq(text(input), nb(expected), label);

last('Он сказал правду', 'Он сказал~правду', 'последнее слово');
last('Конец.', 'Конец.', 'одно слово');
last('Два слова', 'Два~слова', 'два слова');
last('текст в доме', 'текст в~доме', 'совпадает с правилом слов');
last('Текст здесь.  ', 'Текст~здесь.  ', 'хвостовые пробелы не мешают');
last('', '', 'пустая строка');

// ---------------------------------------------------------------------------
// Предел длины цепочки (max_chain, по умолчанию 14)
// ---------------------------------------------------------------------------

eq(RULES.max_chain, 14, 'предел по умолчанию');
t('А когда наступал вечер', 'А когда~наступал вечер', 'длинная цепочка рвётся у дальней связи');
t('как над городом', 'как над~городом', 'предлог остаётся при своём слове');
t('а и в доме', 'а~и~в~доме', 'короткая цепочка цела (10)');
t('благодаря тебе', 'благодаря~тебе', 'ровно 14 — клеится');
t('благодаря тебя', 'благодаря~тебя', 'граница включительно');
t('вопреки ожиданиям', 'вопреки ожиданиям', '17 > 14 — не клеится');
t('вопреки ожиданиям', 'вопреки~ожиданиям', 'max_chain: 0 — без предела', { last_word: false, max_chain: 0 });
t('а и в доме', 'а и~в~доме', 'max_chain: 8 — отпускается первая связь', { last_word: false, max_chain: 8 });
t('в достопримечательностях', 'в достопримечательностях', 'одно длинное слово не клеится к предлогу');
t('10 000 000 рублей', '10 000 000~рублей', 'авторские NBSP не рвутся, ближняя связь цела');
t('А. С. Пушкин', 'А.~С.~Пушкин', 'инициалы (12) целы');
last('Он сказал правду', 'Он сказал~правду', 'last_word в пределе');
last('Мы видели достопримечательности', 'Мы видели достопримечательности', 'last_word за пределом не клеится');
eq(glue(['А когда ', 'наступал']), ['А когда~', 'наступал'].map(nb), 'предел работает через части');

// ---------------------------------------------------------------------------
// Отключение правил
// ---------------------------------------------------------------------------

const none = Object.fromEntries(Object.keys(RULES).map(k => [k, false]));
eq(text('в доме он же 5 лет — т. е. А. С. Пушкин', none), 'в доме он же 5 лет — т. е. А. С. Пушкин', 'все правила выключены');
for (let [rule, input, expected] of [
    ['words', 'в доме', 'в~доме'],
    ['particles', 'он же', 'он~же'],
    ['numbers', '5 лет', '5~лет'],
    ['dash', 'лес — дом', 'лес~— дом'],
    ['abbr', 'ул. Мира', 'ул.~Мира'],
    ['initials', 'И. Бродский', 'И.~Бродский'],
    ['last_word', 'Кот спит', 'Кот~спит'],
]) {
    eq(text(input, { ...none, [rule]: true }), nb(expected), `только ${rule}`);
    eq(text(input, { [rule]: false, last_word: false }), input, `без ${rule}`);
}

// ---------------------------------------------------------------------------
// Части: склейка сквозь inline-теги
// ---------------------------------------------------------------------------

const g = (parts, expected, label, rules = off) => eq(glue(parts, rules), expected.map(nb), label);

g(['в ', 'доме'], ['в~', 'доме'], 'пробел в первой части');
g(['в', ' доме'], ['в', '~доме'], 'пробел во второй части');
g(['в', ' ', 'доме'], ['в', '~', 'доме'], 'пробел — отдельная часть');
g(['в ', '\n  ', ' доме'], ['в~', '', 'доме'], 'промежуток на стыке трёх частей');
g(['в', '', ' доме'], ['в', '', '~доме'], 'пустая часть');
g(['жил ', 'в', ' доме'], ['жил ', 'в', '~доме'], 'короткое слово — целая часть');
g(['сло', 'во доме'], ['сло', 'во доме'], 'слово, разрезанное тегом, не путается с «во»');
g(['он ', 'же'], ['он~', 'же'], 'частица в соседней части');
g(['А.', ' ', 'С.', ' Пушкин'], ['А.', '~', 'С.', '~Пушкин'], 'инициалы по частям');
g(['Он сказал ', 'правду'], ['Он сказал~', 'правду'], 'последнее слово в другой части', {});
g([], [], 'нет частей');

{   // число частей и порядок сохраняются на длинном входе
    let parts = Array.from({ length: 50 }, (_, i) => i % 3 ? 'в доме ' : 'и ');
    let out = glue(parts);
    eq(out.length, parts.length, 'длина массива сохраняется');
    eq(out.join('').replace(/ /g, ' ').replace(/ +/g, ' '), parts.join('').replace(/ +/g, ' '),
       'кроме пробелов текст не меняется');
}

// ---------------------------------------------------------------------------
// Идемпотентность и Юникод
// ---------------------------------------------------------------------------

for (let s of ['в доме он же 5 лет — т. е. А. С. Пушкин', 'и т. д. и т. п.', 'Москва — столица России']) {
    let once = text(s);
    eq(text(once), once, `идемпотентность: ${s}`);
}
eq(glue(glue(['в ', 'доме ', 'и ', 'саду'])), glue(['в ', 'доме ', 'и ', 'саду']), 'идемпотентность по частям');

t('в 😀 доме', 'в~😀 доме', 'эмодзи (суррогатная пара) не ломает индексы');
g(['😀 ', 'в доме'], ['😀 ', 'в~доме'], 'суррогаты в соседней части');
t('в доме', 'в доме', 'уже склеенное не меняется');

console.log(`Пройдено: ${passed}, провалено: ${failed}`);
if (failed) process.exit(1);
